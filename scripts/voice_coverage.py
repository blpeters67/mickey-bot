"""
The voice DJ's command coverage table: every command the bot has, and how it
works by voice — the voice operation that runs it (through the same code as
typed), or why it stays typed-only. Built from core/voice_tools.py, so it
can't drift from what the planner is actually allowed to do.

    venv/bin/python scripts/voice_coverage.py [--out VOICE_COVERAGE.md]
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("DISCORD_TOKEN", "coverage")


def all_commands() -> dict[str, tuple[str, object]]:
    """qualified name → (cog class name, command) for every prefix/hybrid
    command the cogs declare, plus the right-click message menus."""
    import bot as botmod
    from discord.ext import commands
    out: dict[str, tuple[str, object]] = {}
    for mod_name in botmod.COG_MODULES:
        mod = importlib.import_module(mod_name)
        for _n, cls in inspect.getmembers(mod, inspect.isclass):
            if issubclass(cls, commands.Cog) and cls.__module__ == mod.__name__:
                stack = list(cls.__cog_commands__)
                while stack:
                    c = stack.pop()
                    out[c.qualified_name] = (cls.__name__, c)
                    if isinstance(c, commands.Group):
                        stack.extend(c.commands)
    src = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "cogs", "downloads.py"), encoding="utf-8").read()
    for m in re.findall(r'ContextMenu\(name="([^"]+)"', src):
        out[f"menu:{m}"] = ("Downloads", None)
    return out


def table() -> str:
    from core.voice_tools import OPS, coverage_table
    cmds = all_commands()
    rows = coverage_table(cmds)
    by_cog: dict[str, list] = {}
    for name, how, why in rows:
        by_cog.setdefault(cmds[name][0], []).append((name, how, why))
    voice = sum(1 for r in rows if r[1].startswith("voice"))
    typed = sum(1 for r in rows if r[1] == "not by voice")
    lost = [r[0] for r in rows if r[1] == "UNCLASSIFIED"]
    lines = ["# Voice DJ command coverage", "",
             f"{len(rows)} commands: **{voice} by voice**, {typed} typed-only"
             + (f", **{len(lost)} unclassified**" if lost else "") + ".", "",
             "By voice, a command runs through the same code as typed — the shared queue "
             "operations (core/queue_ops.py) or the command itself, invoked as the speaker "
             "with its own checks (permissions, cooldowns, consent). Ones that ask first "
             "(stop, clear, a very loud volume) still wait for a spoken yes. Typed-only "
             "commands are named to the planner, so asking for one by voice gets the "
             "reason instead of a pretend success.", "",
             "Generated by `scripts/voice_coverage.py` from `core/voice_tools.py`.", ""]
    for cog in sorted(by_cog):
        lines += [f"## {cog}", "", "| Command | By voice | How / why not |", "|---|---|---|"]
        for name, how, why in sorted(by_cog[cog]):
            shown = name if name.startswith("menu:") else f"`{name}`"
            lines.append(f"| {shown} | {how.replace('voice: ', '✅ ') if how.startswith('voice') else '— typed'} "
                         f"| {why} |")
        lines.append("")
    lines += ["## Voice-only operations", "",
              "Operations with no single typed command behind them:", "",
              "| Operation | What it does |", "|---|---|"]
    for spec in OPS.values():
        if not spec.covers:
            lines.append(f"| `{spec.name}` | {spec.doc} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    text = table()
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
